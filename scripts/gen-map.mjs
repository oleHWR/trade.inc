// One-off generator: Natural Earth countries (public domain) -> compact SVG path in src/content/worldMap.ts
import fs from 'node:fs';

const src = process.argv[2] ?? '/tmp/countries.json';
const geo = JSON.parse(fs.readFileSync(src, 'utf8'));
const W = 1000;
const LAT_MAX = 84;
const LAT_MIN = -58;
const H = Math.round((W * (LAT_MAX - LAT_MIN)) / 360);
const px = (lon) => ((lon + 180) / 360) * W;
const py = (lat) => ((LAT_MAX - Math.max(LAT_MIN, Math.min(LAT_MAX, lat))) / (LAT_MAX - LAT_MIN)) * H;
const f = (n) => (Math.round(n * 10) / 10).toString();

function ring(r) {
  const pts = [];
  let last = '';
  for (const [lon, lat] of r) {
    if (lat < LAT_MIN - 1) continue; // drop Antarctica
    const p = `${f(px(lon))} ${f(py(lat))}`;
    if (p !== last) pts.push(p);
    last = p;
  }
  if (pts.length < 3) return '';
  return 'M' + pts.join('L') + 'Z';
}

const parts = [];
for (const ft of geo.features) {
  const g = ft.geometry;
  if (!g) continue;
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  let d = '';
  for (const poly of polys) for (const r of poly) d += ring(r);
  if (d) parts.push(d);
}
const out =
  `// Generated by scripts/gen-map.mjs from Natural Earth 110m (public domain). Do not edit.\n` +
  `export const MAP_WIDTH = ${W};\nexport const MAP_HEIGHT = ${H};\nexport const MAP_LAT_MAX = ${LAT_MAX};\nexport const MAP_LAT_MIN = ${LAT_MIN};\n` +
  `export const COUNTRY_PATHS: string[] = ${JSON.stringify(parts)};\n`;
fs.writeFileSync('src/content/worldMap.ts', out);
console.log('countries', parts.length, 'bytes', out.length, 'H', H);
